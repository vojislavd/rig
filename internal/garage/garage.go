// Package garage runs Garage, a small S3-compatible object store, for
// sites that store files. It replaces MinIO.
package garage

import (
	"crypto/rand"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"

	"github.com/vojislavd/rig/internal/safepath"
)

// Loopback addresses. S3 is reached by sites through nginx
// (https://files.<site>.localhost); RPC and admin are Garage's own.
const (
	S3Addr    = "127.0.0.1:3900"
	RPCAddr   = "127.0.0.1:3901"
	AdminAddr = "127.0.0.1:3903"
	Region    = "garage"
	UnitName  = "rig-garage.service"
)

// Secrets are Garage's own credentials, kept only in its config file.
type Secrets struct {
	RPC     string // shared cluster secret (64 hex characters)
	Admin   string // bearer token for the admin API
	Metrics string // bearer token for /metrics
}

var hex64 = regexp.MustCompile(`^[0-9a-f]{64}$`)

func (s Secrets) check() error {
	for _, v := range []string{s.RPC, s.Admin, s.Metrics} {
		if !hex64.MatchString(v) {
			return errors.New("garage secrets must be 64 lowercase hex characters")
		}
	}
	return nil
}

// NewSecrets returns fresh random secrets.
func NewSecrets() (Secrets, error) {
	var s Secrets
	for _, dst := range []*string{&s.RPC, &s.Admin, &s.Metrics} {
		b := make([]byte, 32)
		if _, err := rand.Read(b); err != nil {
			return Secrets{}, err
		}
		*dst = hex.EncodeToString(b)
	}
	return s, nil
}

// Config returns garage.toml for data in dataDir (~/.local/share/rig/garage).
//
// Security: every listener is on 127.0.0.1. The admin API and metrics need
// their tokens (a request without one gets 403). The file holds the
// secrets, so it is written 0600.
func Config(dataDir string, s Secrets) ([]byte, error) {
	return config(dataDir, s, S3Addr, RPCAddr, AdminAddr)
}

// config is Config with the listen addresses as parameters (tests use
// other ports).
func config(dataDir string, s Secrets, s3, rpc, admin string) ([]byte, error) {
	if err := safepath.Check(dataDir); err != nil {
		return nil, err
	}
	if err := s.check(); err != nil {
		return nil, err
	}
	return []byte(fmt.Sprintf(`# Generated by rig. Do not edit: rig rewrites this file. Keep private (0600).
metadata_dir = "%[1]s/meta"
data_dir = "%[1]s/data"
db_engine = "sqlite"
replication_factor = 1

rpc_bind_addr = "%[2]s"
rpc_public_addr = "%[2]s"
rpc_secret = "%[5]s"

[s3_api]
s3_region = "%[6]s"
api_bind_addr = "%[3]s"

[admin]
api_bind_addr = "%[4]s"
admin_token = "%[7]s"
metrics_token = "%[8]s"
`, dataDir, rpc, s3, admin, s.RPC, Region, s.Admin, s.Metrics)), nil
}

var secretLine = regexp.MustCompile(`(?m)^(rpc_secret|admin_token|metrics_token) = "([0-9a-f]{64})"$`)

// LoadSecrets reads the secrets back from an existing garage.toml. A
// missing file returns an error matching fs.ErrNotExist.
func LoadSecrets(path string) (Secrets, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return Secrets{}, err
	}
	var s Secrets
	for _, m := range secretLine.FindAllStringSubmatch(string(data), -1) {
		switch m[1] {
		case "rpc_secret":
			s.RPC = m[2]
		case "admin_token":
			s.Admin = m[2]
		case "metrics_token":
			s.Metrics = m[2]
		}
	}
	if err := s.check(); err != nil {
		return Secrets{}, fmt.Errorf("%s: %w", path, err)
	}
	return s, nil
}

// Unit returns the user unit that runs Garage with the config at conf and
// data in dataDir.
//
// Security: on demand (no [Install]: never starts at login), sandboxed
// with the home folder hidden except its data folder and (read-only) its
// config file.
func Unit(conf, dataDir string) ([]byte, error) {
	for _, p := range []string{conf, dataDir} {
		if err := safepath.Check(p); err != nil {
			return nil, err
		}
	}
	return []byte(fmt.Sprintf(`# Generated by rig. Do not edit: rig rewrites this file.

[Unit]
Description=rig: Garage S3 storage (S3 %[3]s)

[Service]
Type=simple
ExecStart=/usr/bin/garage -c %[1]s server
Restart=on-failure

ProtectHome=tmpfs
BindPaths=%[2]s
BindReadOnlyPaths=%[1]s

UMask=0077
NoNewPrivileges=yes
ProtectSystem=strict
PrivateTmp=yes
PrivateDevices=yes
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectKernelLogs=yes
ProtectControlGroups=yes
ProtectHostname=yes
ProtectClock=yes
RestrictNamespaces=yes
RestrictRealtime=yes
RestrictSUIDSGID=yes
LockPersonality=yes
MemoryDenyWriteExecute=yes
RestrictAddressFamilies=AF_INET AF_INET6 AF_UNIX
SystemCallArchitectures=native
SystemCallFilter=@system-service
`, conf, dataDir, S3Addr)), nil
}

// DataDirs are the folders Garage needs inside dataDir.
func DataDirs(dataDir string) []string {
	return []string{dataDir, filepath.Join(dataDir, "meta"), filepath.Join(dataDir, "data")}
}
