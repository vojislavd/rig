package nginx

import (
	"errors"
	"fmt"
	"path/filepath"
	"strings"
)

// UnitName is the systemd user unit that runs rig's nginx.
const UnitName = "rig-nginx.service"

// UnitDirs are the folders the nginx unit needs.
type UnitDirs struct {
	Dirs
	Code  string // ~/code: site folders (read-only for nginx)
	Certs string // ~/.local/share/rig/certs: site certificates (read-only)
}

// Unit returns the systemd user unit that runs nginx as the user.
//
// Security: nginx runs as the user, so without a sandbox it could read
// everything the user can (~/.ssh, ~/.gnupg, browser profiles).
// ProtectHome=tmpfs hides all of /home and /run/user; only the folders
// nginx needs are mounted back, read-only except logs and runtime files.
// The other options make the system read-only and block privilege
// changes, kernel tweaks and unusual system calls. User units get these
// through user namespaces; each option is checked in a live run.
func Unit(u UnitDirs) ([]byte, error) {
	if err := u.check(); err != nil {
		return nil, err
	}
	for _, p := range []string{u.Code, u.Certs} {
		if err := checkPath(p); err != nil {
			return nil, err
		}
	}
	// systemd creates these folders itself (RuntimeDirectory=rig/nginx under
	// $XDG_RUNTIME_DIR, StateDirectory=rig/logs under $XDG_STATE_HOME), so
	// the paths in nginx.conf must end the same way.
	if !strings.HasSuffix(u.Runtime, "/rig/nginx") || !strings.HasSuffix(u.Logs, "/rig/logs") {
		return nil, errors.New("nginx runtime and log folders must end in /rig/nginx and /rig/logs")
	}
	conf := filepath.Join(u.Conf, "nginx.conf")
	startupLog := filepath.Join(u.Logs, "nginx-startup.log")
	// -e: startup errors go to rig's log, not root-owned /var/log/nginx.
	// "daemon off": stay in the foreground so systemd tracks the process.
	nginx := fmt.Sprintf("/usr/bin/nginx -e %s -c %s", startupLog, conf)

	return []byte(fmt.Sprintf(`# Generated by rig. Do not edit: rig rewrites this file.

[Unit]
Description=rig: nginx (as you, on %[1]s:%[2]d and :%[3]d)

[Service]
Type=simple
# systemd creates these private folders before the sandbox is set up:
# /run/user/UID/rig/nginx (emptied at logout) and ~/.local/state/rig/logs.
RuntimeDirectory=rig/nginx
RuntimeDirectoryMode=0700
StateDirectory=rig/logs
StateDirectoryMode=0700

ExecStartPre=%[4]s -t -q
ExecStart=%[4]s -g "daemon off;"
ExecReload=%[4]s -t -q
ExecReload=/usr/bin/kill -s HUP $MAINPID
Restart=on-failure

# Hide the whole home folder, then mount back only what nginx needs.
# The runtime folder is rig's whole /run/user/UID/rig, so nginx also
# reaches PHP-FPM's socket even if PHP starts after nginx.
ProtectHome=tmpfs
BindReadOnlyPaths=%[7]s %[8]s %[9]s
BindPaths=%[5]s %[6]s

# Files nginx creates (logs, temp files) are private to the user.
UMask=0077
NoNewPrivileges=yes
ProtectSystem=strict
PrivateTmp=yes
PrivateDevices=yes
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectKernelLogs=yes
ProtectControlGroups=yes
ProtectHostname=yes
ProtectClock=yes
RestrictNamespaces=yes
RestrictRealtime=yes
RestrictSUIDSGID=yes
LockPersonality=yes
MemoryDenyWriteExecute=yes
RestrictAddressFamilies=AF_INET AF_INET6 AF_UNIX
SystemCallArchitectures=native
SystemCallFilter=@system-service

[Install]
WantedBy=default.target
`, ListenAddr, HTTPPort, HTTPSPort, nginx, u.Logs, filepath.Dir(u.Runtime), u.Code, u.Certs, u.Conf)), nil
}
