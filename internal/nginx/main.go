// Package nginx generates the configuration for rig's nginx, which runs
// as the user.
package nginx

import (
	"fmt"

	"github.com/vojislavd/rig/internal/safepath"
)

// Listen addresses. IPv4 loopback only: IPv6 is disabled on this machine,
// and a [::1] listener would stop nginx from starting.
const (
	ListenAddr = "127.0.0.1"
	HTTPPort   = 8080
	HTTPSPort  = 8443
)

// Dirs are the folders the main config refers to.
type Dirs struct {
	Conf    string // ~/.config/rig/nginx: nginx.conf and rig.d/
	Logs    string // ~/.local/state/rig/logs
	Runtime string // /run/user/UID/rig/nginx: pid and temp files
}

// checkPath rejects paths nginx could misread (see safepath.Check).
func checkPath(p string) error {
	return safepath.Check(p)
}

func (d Dirs) check() error {
	for _, p := range []string{d.Conf, d.Logs, d.Runtime} {
		if err := checkPath(p); err != nil {
			return err
		}
	}
	return nil
}

// MainConfig returns nginx.conf.
//
// Security:
//   - No "user" directive: nginx runs as the user who starts it, never root.
//   - Listens only on 127.0.0.1.
//   - Default servers answer any unknown host name with nothing: plain HTTP
//     closes the connection (444), HTTPS refuses the TLS handshake. Only
//     names with a site config in rig.d/ get a response.
//   - server_tokens off: no nginx version in headers or error pages.
func MainConfig(d Dirs) ([]byte, error) {
	if err := d.check(); err != nil {
		return nil, err
	}
	return []byte(fmt.Sprintf(`# Generated by rig. Do not edit: rig rewrites this file.

worker_processes auto;
pid %[3]s/nginx.pid;
error_log %[2]s/nginx-error.log warn;

events {
    worker_connections 1024;
}

http {
    include /etc/nginx/mime.types;
    default_type application/octet-stream;
    types_hash_max_size 4096;
    sendfile on;
    server_tokens off;
    client_max_body_size 100m;

    access_log %[2]s/nginx-access.log;

    # Temp files in the private runtime folder, not /var/lib/nginx (root-owned).
    client_body_temp_path %[3]s/client_body;
    proxy_temp_path       %[3]s/proxy;
    fastcgi_temp_path     %[3]s/fastcgi;
    uwsgi_temp_path       %[3]s/uwsgi;
    scgi_temp_path        %[3]s/scgi;

    # Websocket upgrade header for Reverb routes (empty when not upgrading).
    map $http_upgrade $connection_upgrade {
        default upgrade;
        ''      close;
    }

    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_prefer_server_ciphers off;

    # Unknown host names get nothing.
    server {
        listen %[4]s:%[5]d default_server;
        return 444;
    }
    server {
        listen %[4]s:%[6]d ssl default_server;
        ssl_reject_handshake on;
    }

    # One file per site, written by rig link.
    include %[1]s/rig.d/*.conf;
}
`, d.Conf, d.Logs, d.Runtime, ListenAddr, HTTPPort, HTTPSPort)), nil
}
