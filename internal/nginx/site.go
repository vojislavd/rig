package nginx

import (
	"fmt"
	"path/filepath"
	"regexp"

	"github.com/vojislavd/rig/internal/safepath"
	"github.com/vojislavd/rig/internal/site"
)

// Site holds what one site's nginx config needs.
type Site struct {
	Name   string // site name, e.g. "foo" (served as foo.localhost)
	Dir    string // project folder; nginx serves Dir/public
	Certs  string // folder with <name>.crt and <name>.key
	Socket string // PHP-FPM socket for the site's PHP version
	// ReverbPort, if not 0, adds a route for /app/... (browser websockets)
	// and /apps/... (Laravel's event API) to Reverb on 127.0.0.1:port.
	ReverbPort int
	// S3, if true, adds a server for files.<name>.localhost that forwards
	// only this site's bucket (/rig-<name>/...) to Garage.
	S3 bool
	// S3Addr is Garage's S3 address (127.0.0.1:3900); used if S3 is true.
	S3Addr string
}

// SiteConfigPath is where a site's config lives inside the nginx folder.
func SiteConfigPath(confDir, name string) string {
	return filepath.Join(confDir, "rig.d", name+".conf")
}

// SiteConfig returns the nginx config for one site.
//
// Security:
//   - Only public/index.php is executed. Any other .php file returns 404,
//     so an uploaded script can't run and its source can't be read.
//   - Dotfiles (.env, .git, ...) are never served, except .well-known.
//   - Plain HTTP only redirects to https://<name>.localhost, a fixed name,
//     never to whatever Host header the client sent.
//   - Headers block framing and MIME sniffing; PHP's X-Powered-By is hidden.
//   - No HSTS: browsers would remember it for the name long after rig.
func SiteConfig(s Site) ([]byte, error) {
	if err := site.ValidateName(s.Name); err != nil {
		return nil, err
	}
	for _, p := range []string{s.Dir, s.Certs, s.Socket} {
		if err := safepath.Check(p); err != nil {
			return nil, err
		}
	}
	host := site.Host(s.Name)
	reverb := ""
	if s.ReverbPort != 0 {
		if s.ReverbPort < site.MinReverbPort || s.ReverbPort > site.MaxReverbPort {
			return nil, fmt.Errorf("reverb port %d outside %d-%d", s.ReverbPort, site.MinReverbPort, site.MaxReverbPort)
		}
		reverb = fmt.Sprintf(`
    # Reverb: /app/... (browser websockets) and /apps/... (Laravel's API),
    # forwarded to Reverb on loopback. The Host header is the fixed site
    # name, never the client's.
    location ~ ^/apps?/ {
        proxy_pass http://%[1]s:%[2]d;
        proxy_http_version 1.1;
        proxy_set_header Host %[3]s;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection $connection_upgrade;
        proxy_set_header X-Forwarded-For $remote_addr;
        proxy_set_header X-Forwarded-Proto https;
        proxy_read_timeout 120s;
    }
`, ListenAddr, s.ReverbPort, host)
	}

	files := ""
	if s.S3 {
		if !loopbackAddr.MatchString(s.S3Addr) {
			return nil, fmt.Errorf("S3 address %q must be 127.0.0.1:<port>", s.S3Addr)
		}
		fh, bucket := site.FilesHost(s.Name), site.Bucket(s.Name)
		files = fmt.Sprintf(`
# S3 storage (Garage) for this site. Only this site's bucket is forwarded;
# any other path gets 404 before reaching Garage. The Host header stays the
# fixed name, which S3 request signatures include.
server {
    listen %[1]s:%[2]d ssl;
    http2 on;
    server_name %[3]s;

    ssl_certificate     %[5]s/%[6]s.crt;
    ssl_certificate_key %[5]s/%[6]s.key;

    location = /%[4]s {
        proxy_pass http://%[7]s;
        proxy_set_header Host %[3]s;
    }
    location ^~ /%[4]s/ {
        proxy_pass http://%[7]s;
        proxy_set_header Host %[3]s;
        proxy_request_buffering off;
    }
    location / {
        return 404;
    }
}
`, ListenAddr, HTTPSPort, fh, bucket, s.Certs, s.Name, s.S3Addr)
	}

	return []byte(fmt.Sprintf(`# Generated by rig for site %[1]s. Do not edit: rig rewrites this file.

server {
    listen %[3]s:%[4]d;
    server_name %[2]s;
    return 301 https://%[2]s$request_uri;
}

server {
    listen %[3]s:%[5]d ssl;
    http2 on;
    server_name %[2]s;

    ssl_certificate     %[7]s/%[1]s.crt;
    ssl_certificate_key %[7]s/%[1]s.key;

    root %[6]s/public;
    index index.php;
    charset utf-8;

    add_header X-Frame-Options "SAMEORIGIN" always;
    add_header X-Content-Type-Options "nosniff" always;
    add_header Referrer-Policy "strict-origin-when-cross-origin" always;

    # Never serve dotfiles (.env, .git, ...), except .well-known.
    location ~ /\.(?!well-known) {
        deny all;
    }
%[9]s
    location / {
        try_files $uri $uri/ /index.php?$query_string;
    }

    location = /favicon.ico { access_log off; log_not_found off; }
    location = /robots.txt  { access_log off; log_not_found off; }

    error_page 404 /index.php;

    # Only the front controller runs PHP.
    location ~ ^/index\.php(/|$) {
        fastcgi_pass unix:%[8]s;
        fastcgi_param SCRIPT_FILENAME $realpath_root$fastcgi_script_name;
        include /etc/nginx/fastcgi_params;
        fastcgi_hide_header X-Powered-By;
    }

    # Any other .php file: not run, not shown.
    location ~ \.php$ {
        return 404;
    }
}
%[10]s`, s.Name, host, ListenAddr, HTTPPort, HTTPSPort, s.Dir, s.Certs, s.Socket, reverb, files)), nil
}

var loopbackAddr = regexp.MustCompile(`^127\.0\.0\.1:[0-9]{1,5}$`)
