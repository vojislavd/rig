// Package worker generates systemd user units for a site's long-running
// artisan processes.
package worker

import (
	"fmt"
	"slices"

	"github.com/vojislavd/rig/internal/safepath"
	"github.com/vojislavd/rig/internal/site"
)

// Kinds are the workers rig knows, with the artisan command each runs.
// Only these exist; the command line is fixed here, never user input.
var Kinds = map[string][]string{
	"queue":    {"queue:work", "--sleep=3", "--tries=3", "--max-time=3600"},
	"schedule": {"schedule:work"},
	// reverb also gets --host=127.0.0.1 --port=N (see Unit).
	"reverb": {"reverb:start"},
}

// KindNames returns the known kinds, sorted.
func KindNames() []string {
	names := make([]string, 0, len(Kinds))
	for k := range Kinds {
		names = append(names, k)
	}
	slices.Sort(names)
	return names
}

// CheckKind rejects unknown worker kinds.
func CheckKind(kind string) error {
	if _, ok := Kinds[kind]; !ok {
		return fmt.Errorf("unknown worker %q (known: %v)", kind, KindNames())
	}
	return nil
}

// UnitName is the systemd user unit for one site worker.
func UnitName(siteName, kind string) string {
	return "rig-" + siteName + "-" + kind + ".service"
}

// Unit returns the systemd user unit that runs kind for the site in dir
// with the given PHP CLI binary.
//
// Workers run only on demand: the unit has no [Install] section, so it
// can't be enabled and never starts at login. rig worker start/stop
// control it, and logging out stops it.
//
// Security: the worker sees only its own project folder. ProtectHome=tmpfs
// hides all of /home and /run/user, and only dir is mounted back
// (writable: Laravel writes storage/ and caches). So a compromised job in
// one project can't read other projects, ~/.ssh or rig's keys. It keeps
// network access (APIs, MariaDB over 127.0.0.1, mail). No
// MemoryDenyWriteExecute: PHP's PCRE JIT needs it.
//
// For reverb, port is the site's Reverb port and the server is forced onto
// 127.0.0.1 on the command line. Reverb's own default is 0.0.0.0 (every
// network interface), which would expose it to the local network. For
// other kinds, port must be 0.
func Unit(siteName, dir, kind, phpCLI string, port int) ([]byte, error) {
	if err := site.ValidateName(siteName); err != nil {
		return nil, err
	}
	if err := CheckKind(kind); err != nil {
		return nil, err
	}
	for _, p := range []string{dir, phpCLI} {
		if err := safepath.Check(p); err != nil {
			return nil, err
		}
	}
	cmd := phpCLI + " artisan"
	for _, a := range Kinds[kind] {
		cmd += " " + a
	}
	switch {
	case kind == "reverb" && (port < site.MinReverbPort || port > site.MaxReverbPort):
		return nil, fmt.Errorf("reverb needs a port in %d-%d", site.MinReverbPort, site.MaxReverbPort)
	case kind == "reverb":
		cmd += fmt.Sprintf(" --host=127.0.0.1 --port=%d", port)
	case port != 0:
		return nil, fmt.Errorf("%s worker takes no port", kind)
	}

	return []byte(fmt.Sprintf(`# Generated by rig. Do not edit: rig rewrites this file.

[Unit]
Description=rig: %[1]s %[2]s worker

[Service]
Type=simple
WorkingDirectory=%[3]s
ExecStart=%[4]s
# Workers exit on purpose (e.g. queue:work --max-time) and must come back.
Restart=always
RestartSec=3

# Hide the whole home folder; mount back only this project.
ProtectHome=tmpfs
BindPaths=%[3]s

UMask=0077
NoNewPrivileges=yes
ProtectSystem=strict
PrivateTmp=yes
PrivateDevices=yes
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectKernelLogs=yes
ProtectControlGroups=yes
ProtectHostname=yes
ProtectClock=yes
RestrictNamespaces=yes
RestrictRealtime=yes
RestrictSUIDSGID=yes
LockPersonality=yes
RestrictAddressFamilies=AF_INET AF_INET6 AF_UNIX
SystemCallArchitectures=native
SystemCallFilter=@system-service
`, siteName, kind, dir, cmd)), nil
}
