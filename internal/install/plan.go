// Package install builds and applies rig's one-time privileged setup.
// It is the only part of rig that uses sudo.
package install

import (
	"errors"
	"fmt"
	"io"
	"io/fs"
	"path/filepath"
	"regexp"
	"strings"
)

// Kind says what an Action does.
type Kind int

const (
	WriteFile  Kind = iota // write Content to Path, owned by root
	Run                    // run Argv as root
	RemoveFile             // delete Path (no error if it is already gone)
	RemoveDir              // delete the folder Path if it is empty
)

// Action is one privileged change.
type Action struct {
	Kind Kind
	Why  string // shown to the user before anything is applied

	// WriteFile
	Path    string
	Content []byte
	Mode    fs.FileMode

	// Run
	Argv []string // Argv[0] is an absolute path to the program
	// Stdin is fed to the program (e.g. SQL). StdinShown is what the
	// plan displays instead, with secrets replaced.
	Stdin      []byte
	StdinShown []byte

	// Optional actions may fail without stopping the plan, for example
	// stopping a service that isn't installed.
	Optional bool
}

// Plan is an ordered list of privileged changes.
type Plan struct {
	Title   string // e.g. "rig install", used in messages
	Actions []Action
}

// header starts every file rig install writes, so nobody edits them by
// hand.
const header = "# Generated by rig. Do not edit: rig install rewrites this file.\n"

// allowedPaths are the only files rig install may write. filepath.Match
// "*" never matches "/", so no pattern reaches into subfolders.
//
// Security: this list is the hard limit on what root-owned files rig can
// create. A bug or a tampered config can't widen it; changing it means
// changing this code. Each entry needs a reason in a comment and in README.md.
var allowedPaths = []string{
	"/etc/rig/*",
	"/etc/systemd/system/rig-*.service",
	TrustAnchorPath,
}

// InstalledFiles are the root-owned files and folder rig install leaves
// on the system. rig doctor --security checks that each is still owned
// by root and writable only by root.
var InstalledFiles = []string{"/etc/rig", natConfPath, natUnitPath, TrustAnchorPath}

// allowedDirs are the only folders rig install may create or remove.
var allowedDirs = map[string]bool{
	"/etc/rig": true,
}

// allowedPrograms are the only programs a plan may run as root.
var allowedPrograms = map[string]bool{
	"/usr/bin/systemctl": true,
	"/usr/bin/nft":       true,
	"/usr/bin/mariadb":   true,
	updateCATrust:        true,
}

// Validate checks every action against the allowlists and basic rules.
// It must pass before a plan is shown or applied.
func (p *Plan) Validate() error {
	for i, a := range p.Actions {
		if err := a.validate(); err != nil {
			return fmt.Errorf("action %d: %w", i+1, err)
		}
	}
	return nil
}

func (a Action) validate() error {
	if strings.TrimSpace(a.Why) == "" {
		return errors.New("missing reason")
	}
	switch a.Kind {
	case WriteFile, RemoveFile:
		if filepath.Clean(a.Path) != a.Path || !filepath.IsAbs(a.Path) {
			return fmt.Errorf("path %q must be clean and absolute", a.Path)
		}
		if !pathAllowed(a.Path) {
			return fmt.Errorf("path %q is not on the allowlist", a.Path)
		}
		if a.Kind == RemoveFile {
			return nil
		}
		// Only plain permission bits (no setuid/setgid/sticky), and
		// nobody but root may write.
		if a.Mode&^fs.ModePerm != 0 || a.Mode&0o022 != 0 {
			return fmt.Errorf("%s: mode %04o not allowed", a.Path, a.Mode)
		}
		if a.Path == TrustAnchorPath {
			if err := checkTrustAnchor(a.Content); err != nil {
				return err
			}
		}
	case RemoveDir:
		if !allowedDirs[a.Path] {
			return fmt.Errorf("folder %q is not on the allowlist", a.Path)
		}
	case Run:
		if len(a.Argv) == 0 {
			return errors.New("empty command")
		}
		if !allowedPrograms[a.Argv[0]] {
			return fmt.Errorf("program %q is not on the allowlist", a.Argv[0])
		}
	default:
		return fmt.Errorf("unknown action kind %d", a.Kind)
	}
	return nil
}

func pathAllowed(path string) bool {
	for _, pattern := range allowedPaths {
		if ok, _ := filepath.Match(pattern, path); ok {
			return true
		}
	}
	return false
}

// Render writes the plan in a human-readable form. With showFiles, the
// full content of every file is printed too.
func (p *Plan) Render(w io.Writer, showFiles bool) {
	if len(p.Actions) == 0 {
		fmt.Fprintf(w, "%s: nothing to do.\n", p.Title)
		return
	}
	fmt.Fprintf(w, "%s will make these changes, each through sudo:\n", p.Title)
	for i, a := range p.Actions {
		fmt.Fprintln(w)
		switch a.Kind {
		case WriteFile:
			fmt.Fprintf(w, "%3d. write %s (root, %04o, %d bytes)\n", i+1, a.Path, a.Mode, len(a.Content))
			if showFiles {
				fmt.Fprintf(w, "     ---- content ----\n%s     ---- end ----\n", indent(a.Content))
			}
		case Run:
			fmt.Fprintf(w, "%3d. run   %s\n", i+1, quoteArgs(a.Argv))
			if a.Stdin != nil {
				fmt.Fprintf(w, "     with %d bytes on stdin (secrets hidden in --show)\n", len(a.Stdin))
				if showFiles {
					fmt.Fprintf(w, "     ---- stdin ----\n%s     ---- end ----\n", indent(a.StdinShown))
				}
			}
		case RemoveFile:
			fmt.Fprintf(w, "%3d. remove %s\n", i+1, a.Path)
		case RemoveDir:
			fmt.Fprintf(w, "%3d. remove folder %s (only if empty)\n", i+1, a.Path)
		}
		fmt.Fprintf(w, "     why: %s\n", a.Why)
		if a.Optional {
			fmt.Fprintln(w, "     (may fail harmlessly, e.g. if already gone)")
		}
	}
}

// indent prefixes every line with spaces, so file content stands apart
// from the plan text.
func indent(content []byte) string {
	var b strings.Builder
	for _, line := range strings.SplitAfter(string(content), "\n") {
		if line != "" {
			b.WriteString("     | " + line)
		}
	}
	if !strings.HasSuffix(b.String(), "\n") {
		b.WriteString("\n")
	}
	return b.String()
}

// safeArg matches arguments that read the same with or without quotes.
var safeArg = regexp.MustCompile(`^[A-Za-z0-9@%+=:,./_-]+$`)

// quoteArgs joins argv for display, quoting anything unusual so the
// output can't be misread (or carry terminal control characters).
func quoteArgs(argv []string) string {
	parts := make([]string, len(argv))
	for i, arg := range argv {
		if safeArg.MatchString(arg) {
			parts[i] = arg
		} else {
			parts[i] = fmt.Sprintf("%q", arg)
		}
	}
	return strings.Join(parts, " ")
}

// Inputs are the machine-specific values the install plan needs.
type Inputs struct {
	CACert       []byte // rig's CA certificate (DER), added to the trust store
	DBSetup      []byte // SQL creating rig's MariaDB admin account and procedures
	DBSetupShown []byte // the same SQL with the password hidden, for display
}

// Build returns the plan for this machine.
//
// Order: write every file first, then rebuild the trust store, set up
// MariaDB, then one daemon-reload so systemd sees all new units, then
// enable and start them.
func Build(in Inputs) *Plan {
	p := &Plan{Title: "rig install"}
	p.Actions = append(p.Actions, natFiles()...)
	p.Actions = append(p.Actions, trustActions(in.CACert)...)
	p.Actions = append(p.Actions, trustRefresh())
	p.Actions = append(p.Actions, Action{
		Kind: Run, Argv: []string{"/usr/bin/mariadb"},
		Stdin: in.DBSetup, StdinShown: in.DBSetupShown,
		Why: "create rig's MariaDB account: full rights on rig_* databases only, plus two checked helper procedures for per-site users",
	})

	var units []string
	for _, a := range p.Actions {
		if a.Kind == WriteFile && strings.HasPrefix(a.Path, "/etc/systemd/system/") {
			units = append(units, filepath.Base(a.Path))
		}
	}
	if len(units) == 0 {
		return p
	}
	p.Actions = append(p.Actions,
		Action{
			Kind: Run, Argv: []string{"/usr/bin/systemctl", "daemon-reload"},
			Why: "make systemd read the new unit files",
		},
		Action{
			Kind: Run, Argv: append([]string{"/usr/bin/systemctl", "enable", "--now"}, units...),
			Why: "start these services now and at every boot",
		},
	)
	return p
}
