// Package db manages rig's MariaDB access: one database and one user per
// site, created through root-owned procedures.
package db

import (
	"crypto/rand"
	"crypto/sha1"
	"encoding/hex"
	"errors"
	"fmt"
	"math/big"
	"regexp"
	"strings"

	"github.com/vojislavd/rig/internal/site"
)

// AdminUser is rig's MariaDB account. It has no "_" after "rig", so no
// site user (always "rig_<site>") can ever have the same name.
const AdminUser = "rigadmin"

// procSchema holds the helper procedures. It does not match `rig\_%`, so
// rigadmin's rights on site databases don't cover it.
const procSchema = "rigsys"

// Name returns the database and user name for a site: hyphens become
// underscores, so "my-shop" -> "rig_my_shop". Site names never contain
// "_", so two sites can't map to the same name.
func Name(siteName string) (string, error) {
	if err := site.ValidateName(siteName); err != nil {
		return "", err
	}
	return "rig_" + strings.ReplaceAll(siteName, "-", "_"), nil
}

const passwordChars = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"

// passwordLen gives about 238 bits of randomness (40 chars from 62).
const passwordLen = 40

// NewPassword returns a random password of letters and digits. Only those
// characters are allowed, so a password can never break out of the quotes
// it is placed in.
func NewPassword() (string, error) {
	b := make([]byte, passwordLen)
	max := big.NewInt(int64(len(passwordChars)))
	for i := range b {
		n, err := rand.Int(rand.Reader, max)
		if err != nil {
			return "", err
		}
		b[i] = passwordChars[n.Int64()]
	}
	return string(b), nil
}

var validPassword = regexp.MustCompile(`^[A-Za-z0-9]{32,128}$`)

func checkPassword(p string) error {
	if !validPassword.MatchString(p) {
		return errors.New("password must be 32-128 letters and digits")
	}
	return nil
}

// Hash returns MariaDB's stored form of a password (mysql_native_password:
// "*" + hex(SHA1(SHA1(password)))). rig puts only this hash into SQL, so a
// statement echoed in an error message never shows the password itself.
// The hash alone is not enough to log in.
func Hash(password string) (string, error) {
	if err := checkPassword(password); err != nil {
		return "", err
	}
	first := sha1.Sum([]byte(password))
	second := sha1.Sum(first[:])
	return "*" + strings.ToUpper(hex.EncodeToString(second[:])), nil
}

// AdminSetupSQL returns the SQL rig install runs as MariaDB root (through
// sudo, sent on stdin). It is safe to run again: it updates the password
// and replaces the procedures.
//
// Security: rigadmin gets
//   - all rights on databases named rig_<something>, and
//   - EXECUTE on two procedures, nothing else. Notably not CREATE USER,
//     which in MariaDB would also allow changing root's password.
//
// The procedures run as root (SQL SECURITY DEFINER) but accept only a
// name matching ^rig_[a-z0-9]+(_[a-z0-9]+)*$ (case-sensitive, at most 64
// characters) and a password hash like *0123...ABCD (41 characters).
// Those checks make the dynamic SQL inside them safe: nothing else can be
// injected. No plaintext password ever appears in the SQL (see Hash).
func AdminSetupSQL(adminPassword string) ([]byte, error) {
	adminHash, err := Hash(adminPassword)
	if err != nil {
		return nil, err
	}
	return []byte(fmt.Sprintf(`-- Generated by rig. Run as MariaDB root by rig install.
CREATE DATABASE IF NOT EXISTS %[1]s;

CREATE USER IF NOT EXISTS '%[2]s'@'localhost' IDENTIFIED BY PASSWORD '%[3]s';
ALTER USER '%[2]s'@'localhost' IDENTIFIED BY PASSWORD '%[3]s';
GRANT ALL PRIVILEGES ON `+"`rig\\_%%`"+`.* TO '%[2]s'@'localhost';

DELIMITER ;;

CREATE OR REPLACE DEFINER='root'@'localhost' PROCEDURE %[1]s.create_site(
    IN db VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin,
    IN pwhash VARCHAR(41) CHARACTER SET ascii COLLATE ascii_bin)
SQL SECURITY DEFINER
BEGIN
    IF db IS NULL OR db NOT REGEXP '^rig_[a-z0-9]+(_[a-z0-9]+)*$' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'rig: invalid site database name';
    END IF;
    IF pwhash IS NULL OR pwhash NOT REGEXP '^[*][0-9A-F]{40}$' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'rig: invalid password hash';
    END IF;
    SET @rig_q = CONCAT('CREATE DATABASE IF NOT EXISTS `+"`"+`', db, '`+"`"+` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci');
    PREPARE rig_s FROM @rig_q; EXECUTE rig_s; DEALLOCATE PREPARE rig_s;
    SET @rig_q = CONCAT('CREATE USER IF NOT EXISTS ''', db, '''@''localhost'' IDENTIFIED BY PASSWORD ''', pwhash, '''');
    PREPARE rig_s FROM @rig_q; EXECUTE rig_s; DEALLOCATE PREPARE rig_s;
    SET @rig_q = CONCAT('ALTER USER ''', db, '''@''localhost'' IDENTIFIED BY PASSWORD ''', pwhash, '''');
    PREPARE rig_s FROM @rig_q; EXECUTE rig_s; DEALLOCATE PREPARE rig_s;
    SET @rig_q = CONCAT('GRANT ALL PRIVILEGES ON `+"`"+`', db, '`+"`"+`.* TO ''', db, '''@''localhost''');
    PREPARE rig_s FROM @rig_q; EXECUTE rig_s; DEALLOCATE PREPARE rig_s;
    SET @rig_q = NULL;
END;;

CREATE OR REPLACE DEFINER='root'@'localhost' PROCEDURE %[1]s.drop_site(
    IN db VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin)
SQL SECURITY DEFINER
BEGIN
    IF db IS NULL OR db NOT REGEXP '^rig_[a-z0-9]+(_[a-z0-9]+)*$' THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'rig: invalid site database name';
    END IF;
    SET @rig_q = CONCAT('DROP DATABASE IF EXISTS `+"`"+`', db, '`+"`"+`');
    PREPARE rig_s FROM @rig_q; EXECUTE rig_s; DEALLOCATE PREPARE rig_s;
    SET @rig_q = CONCAT('DROP USER IF EXISTS ''', db, '''@''localhost''');
    PREPARE rig_s FROM @rig_q; EXECUTE rig_s; DEALLOCATE PREPARE rig_s;
END;;

DELIMITER ;

GRANT EXECUTE ON PROCEDURE %[1]s.create_site TO '%[2]s'@'localhost';
GRANT EXECUTE ON PROCEDURE %[1]s.drop_site TO '%[2]s'@'localhost';
`, procSchema, AdminUser, adminHash)), nil
}

// AdminRemoveSQL undoes AdminSetupSQL. Site databases and their users
// stay: they hold the user's data.
func AdminRemoveSQL() []byte {
	return []byte(fmt.Sprintf(`-- Generated by rig. Run as MariaDB root by rig uninstall.
DROP USER IF EXISTS '%[2]s'@'localhost';
DROP DATABASE IF EXISTS %[1]s;
`, procSchema, AdminUser))
}

// Redact replaces the password in SQL for display.
func Redact(sql []byte, password string) []byte {
	if password == "" {
		return sql
	}
	return []byte(strings.ReplaceAll(string(sql), password, "********"))
}
