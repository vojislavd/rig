package db

import (
	"bufio"
	"bytes"
	"errors"
	"fmt"
	"os"
	"strings"

	"github.com/vojislavd/rig/internal/fsutil"
)

// Socket is the MariaDB server socket on Arch.
const Socket = "/run/mysqld/mysqld.sock"

// AdminConfig returns the content of rig's MariaDB login file. The
// mariadb tools read it with --defaults-extra-file, so the password never
// appears on a command line (where other users could see it with ps).
func AdminConfig(password string) ([]byte, error) {
	if err := checkPassword(password); err != nil {
		return nil, err
	}
	return []byte(fmt.Sprintf(`# Generated by rig: rig's MariaDB admin login. Keep private (0600).
[client]
user=%s
password=%s
socket=%s
`, AdminUser, password, Socket)), nil
}

// SaveAdmin writes the login file (0600). The folder must be private.
func SaveAdmin(path, password string) error {
	content, err := AdminConfig(password)
	if err != nil {
		return err
	}
	return fsutil.WriteFileAtomic(path, content, 0o600)
}

// LoadAdmin reads the password from the login file after checking the
// file is private. A missing file returns an error matching
// fs.ErrNotExist.
func LoadAdmin(path string) (string, error) {
	if _, err := os.Lstat(path); err != nil {
		return "", err
	}
	if err := fsutil.CheckPrivate(path, false); err != nil {
		return "", err
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		if pw, ok := strings.CutPrefix(sc.Text(), "password="); ok {
			if err := checkPassword(pw); err != nil {
				return "", fmt.Errorf("%s: %w", path, err)
			}
			return pw, nil
		}
	}
	return "", errors.New(path + ": no password line")
}
