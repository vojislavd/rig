// Package mailpit generates the systemd user unit for Mailpit, which
// catches all mail sent by local sites.
package mailpit

import (
	"fmt"
	"path/filepath"

	"github.com/vojislavd/rig/internal/safepath"
)

// Addresses: loopback only. Mailpit's own defaults are [::]:1025 and
// [::]:8025, every network interface.
const (
	SMTPAddr = "127.0.0.1:1025"
	UIAddr   = "127.0.0.1:8025"
	UIURL    = "http://localhost:8025"
	UnitName = "rig-mailpit.service"
)

// Unit returns the user unit that runs Mailpit with its database in
// dataDir (~/.local/share/rig/mailpit).
//
// Security and privacy:
//   - SMTP and web UI listen on 127.0.0.1 only.
//   - --allowed-hosts localhost: the web UI answers only Host "localhost"
//     (any port) or an IP address, and refuses other names with 403. This
//     stops DNS rebinding: a website whose name suddenly points at
//     127.0.0.1 can't read caught mail through your browser.
//   - No relay options: caught mail can never be sent onwards.
//   - --disable-version-check: Mailpit never contacts the internet.
//   - --block-remote-css-and-fonts: opening a mail loads no remote files.
//   - On demand: no [Install] section, so it never starts at login.
//   - Sandbox: the home folder is hidden except its own data folder.
func Unit(dataDir string) ([]byte, error) {
	if err := safepath.Check(dataDir); err != nil {
		return nil, err
	}
	db := filepath.Join(dataDir, "mailpit.db")
	return []byte(fmt.Sprintf(`# Generated by rig. Do not edit: rig rewrites this file.

[Unit]
Description=rig: Mailpit (SMTP %[1]s, UI %[2]s)

[Service]
Type=simple
ExecStart=/usr/bin/mailpit --smtp %[1]s --listen %[2]s --database %[3]s --max 500 --allowed-hosts localhost --disable-version-check --block-remote-css-and-fonts
Restart=on-failure

ProtectHome=tmpfs
BindPaths=%[4]s

UMask=0077
NoNewPrivileges=yes
ProtectSystem=strict
PrivateTmp=yes
PrivateDevices=yes
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectKernelLogs=yes
ProtectControlGroups=yes
ProtectHostname=yes
ProtectClock=yes
RestrictNamespaces=yes
RestrictRealtime=yes
RestrictSUIDSGID=yes
LockPersonality=yes
MemoryDenyWriteExecute=yes
RestrictAddressFamilies=AF_INET AF_INET6 AF_UNIX
SystemCallArchitectures=native
SystemCallFilter=@system-service
`, SMTPAddr, UIAddr, db, dataDir)), nil
}
