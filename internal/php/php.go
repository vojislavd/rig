// Package php generates PHP-FPM pools that run as the user, one per PHP
// version.
package php

import (
	"errors"
	"fmt"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/vojislavd/rig/internal/safepath"
)

// Version is one installed PHP version.
type Version struct {
	Name   string // "8.5"
	Binary string // "/usr/bin/php-fpm"
	CLI    string // "/usr/bin/php", used by workers
}

// Default is the PHP version Arch ships as "php".
var Default = Version{Name: "8.5", Binary: "/usr/bin/php-fpm", CLI: "/usr/bin/php"}

var versionName = regexp.MustCompile(`^[0-9]\.[0-9]{1,2}$`)

// ID is the version without the dot: "8.5" -> "85". Used in file, socket
// and unit names.
func (v Version) ID() string {
	return strings.ReplaceAll(v.Name, ".", "")
}

// UnitName is the systemd user unit for this version.
func (v Version) UnitName() string {
	return "rig-php" + v.ID() + ".service"
}

func (v Version) check() error {
	if !versionName.MatchString(v.Name) {
		return fmt.Errorf("invalid PHP version %q", v.Name)
	}
	return safepath.Check(v.Binary)
}

// Dirs are the folders a pool uses.
type Dirs struct {
	Conf    string // ~/.config/rig/php
	Logs    string // ~/.local/state/rig/logs
	Runtime string // /run/user/UID/rig: the pool gets its own php<ID> folder inside
	Code    string // ~/code: site folders (writable for PHP: storage/, caches)
}

func (d Dirs) check() error {
	for _, p := range []string{d.Conf, d.Logs, d.Runtime, d.Code} {
		if err := safepath.Check(p); err != nil {
			return err
		}
	}
	// systemd creates RuntimeDirectory=rig/php<ID> and StateDirectory=rig/logs.
	if !strings.HasSuffix(d.Runtime, "/rig") || !strings.HasSuffix(d.Logs, "/rig/logs") {
		return errors.New("PHP runtime and log folders must end in /rig and /rig/logs")
	}
	return nil
}

// Socket is the path nginx connects to for this version.
func Socket(d Dirs, v Version) string {
	return filepath.Join(d.Runtime, "php"+v.ID(), "fpm.sock")
}

// ConfPath is the pool config file for this version.
func ConfPath(d Dirs, v Version) string {
	return filepath.Join(d.Conf, "php"+v.ID()+".conf")
}

// PoolConfig returns the php-fpm config for version v.
//
// Security:
//   - No user/group settings: php-fpm runs as the user who starts it.
//   - The socket is mode 0600 in a 0700 folder: only the user (and nginx,
//     running as the user) can send requests to PHP.
//   - Only .php files are executed.
//   - ondemand: no PHP processes exist until a request arrives.
func PoolConfig(d Dirs, v Version) ([]byte, error) {
	if err := d.check(); err != nil {
		return nil, err
	}
	if err := v.check(); err != nil {
		return nil, err
	}
	return []byte(fmt.Sprintf(`; Generated by rig. Do not edit: rig rewrites this file.

[global]
error_log = %[1]s/php%[3]s-fpm.log
daemonize = no

[rig]
listen = %[2]s
listen.mode = 0600

pm = ondemand
pm.max_children = 10
pm.process_idle_timeout = 30s

security.limit_extensions = .php
catch_workers_output = yes
decorate_workers_output = no
`, d.Logs, Socket(d, v), v.ID())), nil
}

// Unit returns the systemd user unit for version v.
//
// Security: like nginx, the whole home folder is hidden and only what
// PHP needs comes back: the code folder (writable, Laravel writes
// storage/ and caches), logs, and its socket folder. PHP keeps network
// access (APIs, MariaDB, Mailpit). MemoryDenyWriteExecute is left out on
// purpose: PHP's PCRE JIT needs executable memory, and blocking it makes
// preg_* functions fail.
func Unit(d Dirs, v Version) ([]byte, error) {
	if err := d.check(); err != nil {
		return nil, err
	}
	if err := v.check(); err != nil {
		return nil, err
	}
	fpm := fmt.Sprintf("%s --fpm-config %s", v.Binary, ConfPath(d, v))
	sockDir := filepath.Dir(Socket(d, v))

	return []byte(fmt.Sprintf(`# Generated by rig. Do not edit: rig rewrites this file.

[Unit]
Description=rig: PHP %[1]s FPM (as you)

[Service]
# simple, not notify: php-fpm's "ready" message goes to a socket under
# /run/user/UID/systemd, which ProtectHome=tmpfs hides. Opening that up
# would weaken the sandbox for a cosmetic gain.
Type=simple
RuntimeDirectory=rig/php%[2]s
RuntimeDirectoryMode=0700
StateDirectory=rig/logs
StateDirectoryMode=0700

ExecStartPre=%[3]s --test
ExecStart=%[3]s --nodaemonize
ExecReload=/usr/bin/kill -s USR2 $MAINPID
Restart=on-failure

# Hide the whole home folder, then mount back only what PHP needs.
ProtectHome=tmpfs
BindPaths=%[4]s %[5]s %[6]s
BindReadOnlyPaths=%[7]s

UMask=0077
NoNewPrivileges=yes
ProtectSystem=strict
PrivateTmp=yes
PrivateDevices=yes
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectKernelLogs=yes
ProtectControlGroups=yes
ProtectHostname=yes
ProtectClock=yes
RestrictNamespaces=yes
RestrictRealtime=yes
RestrictSUIDSGID=yes
LockPersonality=yes
RestrictAddressFamilies=AF_INET AF_INET6 AF_UNIX
SystemCallArchitectures=native
SystemCallFilter=@system-service

[Install]
WantedBy=default.target
`, v.Name, v.ID(), fpm, d.Code, d.Logs, sockDir, d.Conf)), nil
}
